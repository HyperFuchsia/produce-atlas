const GH = 8;
export const LINE_H = 11;

const glyphData = {};
for (const [ch, def] of Object.entries(GLYPHS)) {
  const rows = def.split('/');
  while (rows.length < GH) rows.push('00000');
  let minX = 5;
  let maxX = -1;
  for (const r of rows) {
    for (let x = 0; x < 5; x++) {
      if (r[x] === '1') {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
      }
    }
  }
  if (maxX < 0) { minX = 0; maxX = 1; }
  // Digits and a few symbols keep a fixed advance so columns line up.
  const monospace = /[0-9]/.test(ch);
  glyphData[ch] = {
    rows,
    x0: monospace ? 0 : minX,
    w: monospace ? 5 : maxX - minX + 1,
  };
}

const SPACE_W = 3;
const GAP = 1;

const atlases = new Map();

function buildAtlas(color) {
  const chars = Object.keys(glyphData);
  const c = makeCanvas(chars.length * 6, GH);
  const g = c.getContext('2d');
  g.fillStyle = color;
  const pos = {};
  let x = 0;
  for (const ch of chars) {
    const d = glyphData[ch];
    pos[ch] = x;
    for (let y = 0; y < GH; y++) {
      const row = d.rows[y];
      for (let px = 0; px < d.w; px++) {
        if (row[d.x0 + px] === '1') g.fillRect(x + px, y, 1, 1);
      }
    }
    x += 6;
  }
  const atlas = { canvas: c, pos };
  atlases.set(color, atlas);
  return atlas;
}

function getAtlas(color) {
  return atlases.get(color) || buildAtlas(color);
}

export function charWidth(ch) {
  if (ch === ' ') return SPACE_W + GAP;
  const d = glyphData[ch];
  return d ? d.w + GAP : SPACE_W + GAP;
}

export function textWidth(str) {
  let w = 0;
  for (const ch of String(str)) w += charWidth(ch);
  return Math.max(0, w - GAP);
}

/**
 * Draw text. `shadow` paints a 1px offset copy first, which is what gives the
 * GBA menus their embossed look.
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const color = opts.color || '#382c22';
  const shadow = opts.shadow === undefined ? '#c8b8a0' : opts.shadow;
  str = String(str);
  if (shadow) drawRaw(ctx, str, x + 1, y + 1, shadow, opts.maxChars);
  drawRaw(ctx, str, x, y, color, opts.maxChars);
  return textWidth(opts.maxChars !== undefined ? str.slice(0, opts.maxChars) : str);
}

function drawRaw(ctx, str, x, y, color, maxChars) {
  const atlas = getAtlas(color);
  const n = maxChars === undefined ? str.length : Math.min(str.length, maxChars);
  let cx = x;
  for (let i = 0; i < n; i++) {
    const ch = str[i];
    if (ch === ' ') { cx += SPACE_W + GAP; continue; }
    const d = glyphData[ch];
    if (!d) { cx += SPACE_W + GAP; continue; }
    ctx.drawImage(atlas.canvas, atlas.pos[ch], 0, d.w, GH, cx, y, d.w, GH);
    cx += d.w + GAP;
  }
  return cx - x;
}

export function drawTextCentered(ctx, str, cx, y, opts = {}) {
  drawText(ctx, str, Math.round(cx - textWidth(str) / 2), y, opts);
}

export function drawTextRight(ctx, str, rx, y, opts = {}) {
  drawText(ctx, str, Math.round(rx - textWidth(str)), y, opts);
}
